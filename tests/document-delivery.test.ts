describe("Tiered delivery", () => {
  it("delivers a standard document to a standard entitlement", async () => {
    const grant = await issueDocumentDownload(standardUid, docs.standard);
    expect(grant).not.toBeNull();
    const fetched = await fetchSigned(grant!.signedUrl);
    expect(fetched.status).toBe(200);
    expect(fetched.body).toBe(BODIES[docs.standard]);
  });

  it("refuses a diligence document to a standard entitlement", async () => {
    expect(await issueDocumentDownload(standardUid, docs.diligence)).toBeNull();
  });

  it("delivers both standard and diligence documents to a diligence entitlement", async () => {
    const standard = await issueDocumentDownload(diligenceUid, docs.standard);
    const diligence = await issueDocumentDownload(diligenceUid, docs.diligence);
    expect(standard).not.toBeNull();
    expect(diligence).not.toBeNull();
    expect((await fetchSigned(diligence!.signedUrl)).body).toBe(BODIES[docs.diligence]);
  });

  it("refuses an internal document at every tier", async () => {
    expect(await issueDocumentDownload(standardUid, docs.internal)).toBeNull();
    expect(await issueDocumentDownload(diligenceUid, docs.internal)).toBeNull();
  });

  it("never lists an internal document to an investor either", async () => {
    const listed = await loadPortalDocuments(diligenceUid, versionId);
    expect(listed.map((d) => d.title)).not.toContain("P6 Internal IC Memo");
    expect(listed.some((d) => (d as unknown as Record<string, unknown>).storagePath !== undefined))
      .toBe(false);
  });

  it("hands the investor no storage path in the document projection", async () => {
    const listed = await loadPortalDocuments(standardUid, versionId);
    expect(listed.length).toBeGreaterThan(0);
    for (const document of listed) {
      expect(Object.keys(document)).toEqual(
        expect.not.arrayContaining(["storagePath", "storage_path"]));
      expect(JSON.stringify(document)).not.toContain("publications/");
    }
  });
});

