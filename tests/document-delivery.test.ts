describe("The private document store", () => {
  it("keeps the bucket private, so no object has a public URL", async () => {
    const { isPublic } = await ensureDocumentBucket();
    expect(isPublic).toBe(false);
  });

  it("refuses a public-object URL even when the object exists", async () => {
    const rows = await adminQuery<{ storage_path: string }>(
      "select storage_path from publication_documents where document_id = $1", [docs.standard]);
    const publicUrl =
      `${process.env.NEXT_PUBLIC_SUPABASE_URL}/storage/v1/object/public/` +
      `${DOCUMENT_BUCKET}/${rows[0].storage_path}`;
    const response = await fetch(publicUrl);
    expect(response.ok).toBe(false);
  });

  it("generates a random object path that borrows nothing from the file name", () => {
    const a = newObjectPath(versionId, "application/pdf");
    const b = newObjectPath(versionId, "application/pdf");
    expect(a).not.toEqual(b);
    expect(a.startsWith(`publications/${versionId}/`)).toBe(true);
    expect(a.endsWith(".pdf")).toBe(true);
    // The random segment is a UUID, so nothing about it is guessable.
    const segment = a.slice(`publications/${versionId}/`.length, -".pdf".length);
    expect(segment).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/);
  });

  it("validates the type and the size of an upload before storing it", () => {
    expect(checkUpload("application/pdf", 1024).ok).toBe(true);
    expect(checkUpload("application/pdf; charset=binary", 1024).ok).toBe(true);
    expect(checkUpload("APPLICATION/PDF", 1024).ok).toBe(true);

    expect(checkUpload("application/x-msdownload", 1024).ok).toBe(false);
    expect(checkUpload("text/html", 1024).ok).toBe(false);
    expect(checkUpload("", 1024).ok).toBe(false);
    expect(checkUpload("application/pdf", 0).ok).toBe(false);
    expect(checkUpload("application/pdf", MAX_DOCUMENT_BYTES + 1).ok).toBe(false);
    expect(checkUpload("application/pdf", MAX_DOCUMENT_BYTES).ok).toBe(true);
  });

  it("never lets a prototype key masquerade as an allowed type", () => {
    expect(checkUpload("constructor", 1024).ok).toBe(false);
    expect(checkUpload("__proto__", 1024).ok).toBe(false);
  });
});

