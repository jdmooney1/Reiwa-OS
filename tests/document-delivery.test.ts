describe("Removing a document", () => {
  it("deletes the stored object along with the row", async () => {
    const version = (await draft("P6 Disposable Court")).versionId;
    const documentId = await attach(version, "P6 Disposable", "standard", "DISPOSABLE-BYTES");
    const before = await adminQuery<{ storage_path: string }>(
      "select storage_path from publication_documents where document_id = $1", [documentId]);
    const storagePath = before[0].storage_path;
    expect(await signDocumentObject(storagePath)).not.toBeNull();

    const returned = await removePublicationDocument(adminSession, documentId);
    expect(returned).toBe(storagePath);

    const { deleteDocumentObject } = await import("@/lib/documents/storage");
    await deleteDocumentObject(returned!);

    // The object is gone, so nothing can be signed for it any more, and the row
    // that was the only record of its location is gone with it.
    expect(await signDocumentObject(storagePath)).toBeNull();
    const remaining = await adminQuery<{ n: string }>(
      "select count(*)::text as n from publication_documents where document_id = $1", [documentId]);
    expect(Number(remaining[0].n)).toBe(0);
  });

  it("reports nothing to remove when the row was already gone", async () => {
    expect(await removePublicationDocument(
      adminSession, "00000000-0000-4000-8000-000000000001")).toBeNull();
  });
});
