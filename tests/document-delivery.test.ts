describe("The activity trail", () => {
  it("records document_downloaded only after an authorised delivery", async () => {
    const before = await downloadEventCount(docs.diligence);
    const grant = await issueDocumentDownload(diligenceUid, docs.diligence);
    expect(grant).not.toBeNull();
    expect(await downloadEventCount(docs.diligence)).toBe(before + 1);
  });

  it("records the publication and version the document belonged to", async () => {
    await issueDocumentDownload(standardUid, docs.standard);
    const rows = await adminQuery<{ publication_id: string; version_id: string }>(
      `select publication_id, version_id from investor_activity_events
        where document_id = $1 and event_type = 'document_downloaded'
        order by occurred_at desc limit 1`, [docs.standard]);
    expect(rows[0].publication_id).toBe(publicationId);
    expect(rows[0].version_id).toBe(versionId);
  });

  it("records nothing when a download is refused", async () => {
    const before = await downloadEventCount(docs.internal);
    await issueDocumentDownload(standardUid, docs.internal);
    await issueDocumentDownload(diligenceUid, docs.internal);
    await issueDocumentDownload(dormantUid, docs.standard);
    await issueDocumentDownload(suspendedUid, docs.standard);
    expect(await downloadEventCount(docs.internal)).toBe(before);
    // A refused standard download adds nothing on behalf of the refused contact.
    const rows = await adminQuery<{ n: string }>(
      `select count(*)::text as n from investor_activity_events e
         join investor_contacts c on c.investor_contact_id = e.investor_contact_id
        where e.event_type = 'document_downloaded'
          and lower(c.email) in ($1, $2)`, [DORMANT, SUSPENDED]);
    expect(Number(rows[0].n)).toBe(0);
  });
});

