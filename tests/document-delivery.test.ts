const BODIES: Record<string, string> = {};

/**
 * Attach a document to a draft version WITH a real object behind it: the path is
 * generated by the server exactly as the admin upload action generates it.
 */
async function attach(
  version: string, title: string, accessLevel: "standard" | "diligence" | "internal",
  body: string,
): Promise<string> {
  const mimeType = "application/pdf";
  const storagePath = newObjectPath(version, mimeType);
  const bytes = Buffer.from(body, "utf8");
  await putDocumentObject(storagePath, bytes, mimeType);
  const documentId = await addPublicationDocument(adminSession, {
    versionId: version, title, category: "other", storagePath,
    fileName: `${title.toLowerCase().replace(/[^a-z0-9]+/g, "-")}.pdf`,
    mimeType, sizeBytes: bytes.length, accessLevel,
  }, adminUserId);
  BODIES[documentId] = body;
  return documentId;
}

/** Create an internal opportunity + publication and return its draft version. */
async function draft(name: string): Promise<{ publicationId: string; versionId: string }> {
  const opportunityId = await createOpportunity(staff, {
    orgId: await orgIdByName("Meiji Shipping"),
    name, city: "Tokyo", country: "Japan", market: "Tokyo",
    assetType: "office", strategy: "core_plus", currency: "JPY",
    targetPrice: 4_000_000_000, niy: 3.8, targetIrr: 12,
    summary: `${name} — internal summary.`,
  });
  const created = await createPublicationFromOpportunity(adminSession, opportunityId, adminUserId);
  await updateDraftVersion(adminSession, created.versionId, {
    headline: `${name} headline`, highlights: ["A point"],
  });
  return created;
}

/** Fetch a signed URL and report what the object store actually answered. */
async function fetchSigned(signedUrl: string): Promise<{ status: number; body: string }> {
  const response = await fetch(signedUrl);
  return { status: response.status, body: response.ok ? await response.text() : "" };
}

async function downloadEventCount(documentId: string): Promise<number> {
  const rows = await adminQuery<{ n: string }>(
    `select count(*)::text as n from investor_activity_events
      where document_id = $1 and event_type = 'document_downloaded'`, [documentId]);
  return Number(rows[0].n);
}

