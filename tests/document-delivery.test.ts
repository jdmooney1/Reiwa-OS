// ============================================================================
// P6 — secure document delivery, against the real database and object store.
// ----------------------------------------------------------------------------
// The claim under test is narrow and absolute: an investor can obtain the bytes
// of a document if and only if the database says they may, and the only thing
// that ever leaves the server is a sixty-second signed URL.
//
// Every case below goes through the same public entry point the delivery route
// uses — issueDocumentDownload(authUserId, documentId) — so nothing is asserted
// against a private helper that the real request path could bypass. Objects are
// genuinely uploaded and genuinely fetched, so an expiry or a signature is a
// real HTTP outcome rather than a mocked one.
//
// Self-contained fixture (its own opportunities, investor organisations,
// contacts, Auth users and stored objects); nothing seeded is touched.
// ============================================================================
