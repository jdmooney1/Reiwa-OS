describe("Refusals", () => {
  it("refuses a document id that does not exist", async () => {
    expect(await issueDocumentDownload(
      standardUid, "00000000-0000-4000-8000-000000000000")).toBeNull();
  });

  it("refuses a malformed document id without erroring", async () => {
    for (const id of ["../../etc/passwd", "not-a-uuid", "", "'; drop table x; --"]) {
      expect(await issueDocumentDownload(standardUid, id)).toBeNull();
    }
  });

  it("refuses a document belonging to a publication this investor is not entitled to", async () => {
    // The diligence org holds no entitlement to the withdrawn publication.
    expect(await issueDocumentDownload(diligenceUid, withdrawnDocId)).toBeNull();
  });

  it("refuses a withdrawn publication's document to an entitled investor", async () => {
    expect(await issueDocumentDownload(standardUid, withdrawnDocId)).toBeNull();
  });

  it("refuses a deactivated contact", async () => {
    expect(await issueDocumentDownload(dormantUid, docs.standard)).toBeNull();
  });

  it("refuses a contact of a suspended organisation", async () => {
    expect(await issueDocumentDownload(suspendedUid, docs.standard)).toBeNull();
  });

  it("refuses an unknown Auth user", async () => {
    expect(await issueDocumentDownload(
      "11111111-2222-4333-8444-555555555555", docs.standard)).toBeNull();
  });

  it("stops issuing new URLs the moment an entitlement is revoked", async () => {
    const contactOrg = await createInvestorOrganization(adminSession, {
      name: "P6 Revocable Partners", notes: "Created by tests/document-delivery.test.ts.",
    });
    const supabase = createSupabaseAdminClient();
    const uid = await ensureAuthUser(supabase,
      { email: "revoke@p6-docs.example", password: DEMO_PASSWORD, name: "R. Fixture" });
    await createInvestorContact(adminSession, {
      investorOrgId: contactOrg, email: "revoke@p6-docs.example", name: "R. Fixture",
      authUserId: uid,
    });
    await grantEntitlement(adminSession, {
      investorOrgId: contactOrg, publicationId, isVisible: true,
      placement: "featured", documentAccessLevel: "standard",
    }, adminUserId);

    expect(await issueDocumentDownload(uid, docs.standard)).not.toBeNull();

    const entitlements = await listEntitlements(adminSession, contactOrg);
    const mine = entitlements.find((e) => e.publicationId === publicationId)!;
    await revokeEntitlement(adminSession, mine.entitlementId);

    // No cache, no grace period: the very next request is refused.
    expect(await issueDocumentDownload(uid, docs.standard)).toBeNull();
  });
});

